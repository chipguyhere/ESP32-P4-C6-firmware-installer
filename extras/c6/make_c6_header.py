#!/usr/bin/env python3
"""Turn an ESP-Hosted co-processor build into examples/InstallFirmware/c6_firmware.h.

Usage:  python3 make_c6_header.py path/to/network_adapter.bin [output.h [PREFIX]]

PREFIX (default C6) names the symbols: PREFIX_FW_MAJOR ... PREFIX_FIRMWARE.
The installer carries two images: c6_firmware.h (C6, the default) and
c6_firmware_3x.h (C6X, the Advanced choice).

The image this library ships was built with (see README.md here):
    esp-hosted-mcu v2.12.13, its slave/ project, idf.py set-target esp32c6, default
    configuration (SDIO transport, Bluetooth on), ESP-IDF v5.5.5
- the ESP-Hosted version the Arduino ESP32 core 3.3.12 builds its host side against.
The version and IDF strings are read from the image's own app descriptor.
"""
import hashlib, os, struct, sys

src = sys.argv[1]
img = open(src, 'rb').read()
magic, = struct.unpack_from('<I', img, 32)
if img[0] != 0xE9 or magic != 0xABCD5432:
    sys.exit('not an ESP app image with an app descriptor')
field = lambda off, n: img[32 + off:32 + off + n].split(b'\0')[0].decode()
version, project, idf = field(16, 32), field(48, 32), field(112, 32)
major, minor, patch = (int(x) for x in version.lstrip('v').split('.')[:3])   # 3.x says "v3.1.0"
sha = hashlib.sha256(img).digest()
P = sys.argv[3] if len(sys.argv) > 3 else 'C6'

out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(
    os.path.dirname(os.path.abspath(__file__)), '..', '..', 'examples', 'InstallFirmware', 'c6_firmware.h')
with open(out, 'w') as f:
    f.write('// Generated by extras/c6/make_c6_header.py.  Do not edit.\n')
    f.write('// ESP-Hosted co-processor firmware for the ESP32-C6 (%s %s, ESP-IDF %s).\n' % (project, version, idf))
    f.write('// Apache License 2.0 (Espressif esp-hosted-mcu and ESP-IDF); see LICENSE-Apache-2.0.txt.\n')
    f.write('#pragma once\n#include <stdint.h>\n\n')
    f.write('#define %s_FW_MAJOR %d\n#define %s_FW_MINOR %d\n#define %s_FW_PATCH %d\n' % (P, major, P, minor, P, patch))
    f.write('#define %s_FW_VERSION "%d.%d.%d"\n#define %s_FW_IDF "%s"\n\n' % (P, major, minor, patch, P, idf))
    f.write('static const uint8_t %s_FW_SHA256[32] = {%s};\n\n' % (P, ', '.join('0x%02x' % b for b in sha)))
    f.write('static const uint8_t %s_FIRMWARE[%d] = {\n' % (P, len(img)))
    for i in range(0, len(img), 32):
        f.write(','.join('%d' % b for b in img[i:i + 32]) + ',\n')
    f.write('};\n')
print('%s %s (IDF %s), %d bytes, sha256 %s' % (project, version, idf, len(img), sha.hex()))
print('wrote', os.path.normpath(out))
