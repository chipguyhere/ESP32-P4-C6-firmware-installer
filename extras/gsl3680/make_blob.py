#!/usr/bin/env python3
"""Build the GSL3680 firmware blob the installer writes to NVS.

Reads gslx680_firmware_table.h (Silead's table, the source form) and writes
../../examples/InstallFirmware/gsl3680_firmware_blob.h.

Image format (what the display libraries' gsl3680_touch expects, and what its
SHA-256 constant covers): for each page, uint32 page number then the page's
32 uint32 words, all little-endian; 139 pages, 18348 bytes.  The blob is that
image zlib-compressed at level 9.
"""
import hashlib, os, re, struct, sys, zlib

here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'gslx680_firmware_table.h')).read()
entries = [(int(a, 16), int(b, 16)) for a, b in
           re.findall(r'\{\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*\}', src)]

image = bytearray()
expect = None
for off, val in entries:
    if off == 0xF0:
        if expect not in (None, 0x80):
            sys.exit('page ended after %d words' % (expect // 4))
        image += struct.pack('<I', val)
        expect = 0
    else:
        if off != expect:
            sys.exit('word at offset 0x%02x, expected 0x%02x' % (off, expect))
        image += struct.pack('<I', val)
        expect += 4
if expect != 0x80:
    sys.exit('last page incomplete')

sha = hashlib.sha256(image).digest()
blob = zlib.compress(bytes(image), 9)
assert zlib.decompress(blob) == image

out = os.path.join(here, '..', '..', 'examples', 'InstallFirmware', 'gsl3680_firmware_blob.h')
with open(out, 'w') as f:
    f.write('// Generated by extras/gsl3680/make_blob.py from gslx680_firmware_table.h.\n')
    f.write('// Silead GSL3680 firmware, GPL-2.0: see LICENSE-GPL-2.0.txt.  Do not edit.\n')
    f.write('#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n')
    f.write('static const size_t  GSL3680_IMAGE_BYTES = %d;\n' % len(image))
    f.write('static const uint8_t GSL3680_IMAGE_SHA256[32] = {\n')
    for i in range(0, 32, 16):
        f.write('    ' + ', '.join('0x%02x' % b for b in sha[i:i + 16]) + ',\n')
    f.write('};\n\nstatic const uint8_t GSL3680_BLOB[%d] = {\n' % len(blob))
    for i in range(0, len(blob), 16):
        f.write('    ' + ', '.join('0x%02x' % b for b in blob[i:i + 16]) + ',\n')
    f.write('};\n')
print('image %d bytes, blob %d bytes, sha256 %s' % (len(image), len(blob), sha.hex()))
print('wrote', os.path.normpath(out))
